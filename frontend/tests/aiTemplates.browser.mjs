// Run from frontend: node tests/aiTemplates.browser.mjs
// Uses the actual backend catalog, mocked table records and mocked preview responses.
import assert from 'node:assert/strict'
import { execFileSync } from 'node:child_process'
import { existsSync, mkdirSync } from 'node:fs'
import { resolve } from 'node:path'
import { createServer } from 'vite'
import { chromium } from 'playwright'

const python = resolve(existsSync('../backend/.venv/Scripts/python.exe') ? '../backend/.venv/Scripts/python.exe' : '../backend/.venv/bin/python')
const catalog = JSON.parse(execFileSync(python, ['-c', 'import json;from app.services.ai_field_service import scene_catalog;print(json.dumps(scene_catalog(),ensure_ascii=False))'], { cwd: '../backend', encoding: 'utf8', env: { ...process.env, PYTHONIOENCODING: 'utf-8' } }))
const code = `import {createApp,h} from 'vue';import EP from 'element-plus';import 'element-plus/dist/index.css';import '/src/smart/tokens.css';import '/src/smart/buttons.css';import '/src/smart/controls.css';import Editor from '/src/components/smart/ai/AiFieldEditor.vue';createApp({render:()=>h(Editor,{tableId:7,x:900,y:40,field:{label:'工作日天数',options:{scene:'workdays',outputType:'number'}},fields:[{field_name:'start',label:'项目开始',field_type:'date'},{field_name:'end',label:'计划完成',field_type:'date'}],rows:[{id:1,start:'2026-10-12',end:'2026-10-16'}],onSave:v=>window.saved=v})}).use(EP).mount('#app')`
const server = await createServer({ server: { host: '127.0.0.1', port: 5196 }, plugins: [{ name: 'ai-templates-check', resolveId(id) { if (id === '/__templates.js') return id }, load(id) { if (id === '/__templates.js') return code }, configureServer(s) { s.middlewares.use((req, res, next) => { if (req.url !== '/__templates') return next(); res.setHeader('Content-Type', 'text/html'); res.end('<div id="app"></div><script type="module" src="/__templates.js"></script>') }) } }] })
await server.listen()
const browser = await chromium.launch()
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
  const errors = []; page.on('pageerror', error => errors.push(error.message))
  await page.route('**/api/smart/ai/scenes', route => route.fulfill({ json: catalog }))
  await page.route('**/api/smart/tables/7/ai/preview', route => route.fulfill({ json: { config: route.request().postDataJSON().config, preview: [{ inputs: { start: '2026-10-12', end: '2026-10-16' }, output: 5 }] } }))
  await page.goto(server.resolvedUrls.local[0] + '__templates')
  await page.locator('.afe-binding').first().waitFor()
  for (const [index, name] of [[0, '项目开始'], [1, '计划完成']]) {
    await page.locator('.afe-binding').nth(index).locator('.el-select__wrapper').click()
    await page.getByRole('listbox', { name: index === 0 ? '开始日期' : '结束日期', exact: true }).getByRole('option', { name, exact: true }).click()
  }
  await page.getByRole('button', { name: '生成预览', exact: true }).click()
  await page.locator('.asc-inputs').waitFor()
  await page.waitForFunction(() => !document.querySelector('.asc-gen'))
  assert.match(await page.locator('.asc-table').last().textContent(), /5/)
  const output = resolve('../.tmp/ai-reference'); mkdirSync(output, { recursive: true })
  await page.waitForTimeout(300)
  await page.screenshot({ path: output + '/template-editor.png' })
  await page.locator('.scene-trigger').click()
  const popup = page.locator('.ai-scene-picker-pop:visible')
  await page.waitForFunction(() => document.activeElement?.classList.contains('scene-search'))
  assert.equal(await page.locator('.ai-template-detail-pop:visible').count(), 0)
  const menuBefore = await popup.boundingBox()
  await popup.locator('.scene-search').fill('客户阶段')
  await popup.locator('.scene-list button').first().hover()
  const detail = page.locator('.ai-template-detail-pop:visible')
  await detail.locator('.ati-example').waitFor()
  const menuAfter = await popup.boundingBox()
  const detailBox = await detail.boundingBox()
  assert.ok(detailBox.x >= menuAfter.x + menuAfter.width - 1)
  assert.equal(menuBefore.width, menuAfter.width)
  assert.equal(menuBefore.height, menuAfter.height)
  assert.equal(await popup.evaluate(el => el.scrollWidth > el.clientWidth), false)
  assert.equal(await detail.locator('.ati > details').getAttribute('open'), '')
  await detail.hover()
  await page.waitForTimeout(250)
  assert.ok(await detail.isVisible())
  assert.equal(await detail.locator('.ati-usage').getAttribute('open'), '')
  await detail.locator('.ati-usage > summary').click()
  await page.waitForTimeout(250)
  assert.ok(await popup.isVisible())
  assert.ok(await detail.isVisible())
  assert.equal(await detail.locator('.ati-usage').getAttribute('open'), null)
  await detail.locator('.ati-usage > summary').click()
  assert.equal(await detail.locator('.ati-usage').getAttribute('open'), '')
  await detail.locator('.ati-prompt > summary').click()
  assert.ok(await detail.isVisible())
  await detail.locator('.ati-prompt > summary').click()
  await page.waitForTimeout(300)
  assert.equal(await popup.locator('.scene-search').inputValue(), '客户阶段')
  await page.screenshot({ path: output + '/template-library.png' })
  // Include the app's shared popover rule: it previously added another 40px of padding.
  await page.addStyleTag({ content: '.st-tbpanel.el-popover.el-popper { padding: 20px; }' })
  await page.setViewportSize({ width: 1440, height: 864 })
  await popup.locator('.scene-search').fill('评估岗位匹配度')
  await popup.locator('.scene-list button').first().hover()
  await detail.locator('.ati-usage').waitFor()
  await page.waitForTimeout(300)
  assert.equal(await detail.evaluate(el => getComputedStyle(el).paddingTop), '0px')
  assert.equal(await detail.locator('.asp-detail').evaluate(el => el.scrollHeight > el.clientHeight + 1), false)
  const fullDetail = await detail.boundingBox()
  assert.ok(fullDetail.y >= 0 && fullDetail.y + fullDetail.height <= 864)
  const lastNote = await detail.locator('.ati-usage li').last().boundingBox()
  assert.ok(lastNote.y + lastNote.height <= fullDetail.y + fullDetail.height)
  await page.screenshot({ path: output + '/template-full-details.png' })
  await popup.locator('.scene-search').press('Escape')
  await page.locator('.scene-trigger').click()
  await popup.waitFor()
  await page.locator('.afe-name').click()
  await popup.waitFor({ state: 'hidden' })
  for (const width of [900, 390]) {
    await page.setViewportSize({ width, height: 800 })
    await page.waitForTimeout(150)
    const box = await page.locator('.afe').boundingBox()
    assert.ok(box.x >= 0 && box.x + box.width <= width + 1)
    await page.locator('.afe-btn.primary').scrollIntoViewIfNeeded()
    assert.equal((await page.locator('.afe-btn.primary').boundingBox()).height, 28)
  }
  await page.locator('.afe-btn.primary').click()
  const saved = await page.evaluate(() => window.saved)
  assert.deepEqual(saved.config.inputBindings, { start: 'start', end: 'end' })
  assert.deepEqual(errors, [])
  console.log('AI templates: real catalog, role mapping, preview, descriptions, save and responsive layout passed')
} finally { await browser.close(); await server.close() }
